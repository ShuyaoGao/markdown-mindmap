# -*- coding: utf-8 -*-
"""One command to build the static page (play/) and the release zip.

    python -m tools.build              # play/js/credits.js from credits.json + docs/examples/* (needs Node.js)
    python -m tools.build --release    # also write release/<repo>-v<version>.zip (index.html + play/)

play/ is plain HTML + JS: it runs from file:// (double-click play/index.html) without Python.
Nothing in play/ is compiled; this script only writes the generated credits file, exports the three built-in
sample maps as .md / .json / .opml / .mm example files (through the page's own JS under Node; skipped if Node is
not installed) and zips index.html + play/.
"""

import argparse
import json
import re
import shutil
import subprocess
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLAY = ROOT / "play"
RELEASE = ROOT / "release"
ZIP_LIMIT = 15 * 1024 * 1024


def load_credits():
    return json.loads((ROOT / "credits.json").read_text(encoding="utf-8"))


def write_credits_js(credits):
    keep = {k: v for k, v in credits.items() if not k.startswith("_")}
    js = ("/* Generated by tools/build.py from credits.json -- edit credits.json, then rebuild. */\n"
          "window.CREDITS = " + json.dumps(keep, ensure_ascii=False, indent=2) + ";\n")
    out = PLAY / "js" / "credits.js"
    out.write_text(js, encoding="utf-8", newline="\n")
    return out


EXPORT_JS = r"""
const fs = require("fs"), vm = require("vm"), path = require("path");
const ctx = { console, Math, JSON, Map, Set, Date, Infinity };
ctx.globalThis = ctx;
vm.createContext(ctx);
for (const f of ["config.js", "model.js", "markdown.js", "formats.js", "samples.js"]) {
  vm.runInContext(fs.readFileSync(path.join(process.argv[1], f), "utf8"), ctx, { filename: f });
}
const out = {};
ctx.SAMPLES.forEach((s) => {
  const p = ctx.Markdown.parse(s.md), t = new ctx.Model.Tree(p.root);
  out[s.id] = { md: ctx.Markdown.serialize(t.root, { headingLevels: p.headingLevels }).text, json: ctx.Formats.toJSON(t),
                opml: ctx.Formats.toOPML(t), mm: ctx.Formats.toFreeMind(t), nodes: t.count(), depth: t.stats().depth + 1 };
});
process.stdout.write(JSON.stringify(out));
"""
EXAMPLE_NAMES = {"course": "course-tree", "paper": "paper-structure", "week": "week-plan"}


def export_examples():
    node = shutil.which("node")
    if not node:
        print("Node.js not found: docs/examples/ not regenerated")
        return None
    res = subprocess.run([node, "-e", EXPORT_JS, str(PLAY / "js")], capture_output=True, check=True)
    data = json.loads(res.stdout.decode("utf-8"))
    out_dir = ROOT / "docs" / "examples"
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for sid, d in data.items():
        base = EXAMPLE_NAMES.get(sid, sid)
        for ext in ("md", "json", "opml", "mm"):
            p = out_dir / f"{base}.{ext}"
            p.write_text(d[ext], encoding="utf-8", newline="\n")
            written.append(p)
    (out_dir / "README.md").write_text(
        "# 示例文件\n\n页面内置的三张示例地图，由 `python -m tools.build` 从 `play/js/samples.js` 导出，"
        "可以在「我来画 → 打开文件」里直接打开，也可以拿去 FreeMind / Freeplane（.mm）或任何支持 OPML 的大纲工具里试。\n\n"
        "| 示例 | 节点数 | 层数 | 文件 |\n|---|---|---|---|\n"
        + "\n".join(f"| {sid} | {d['nodes']} | {d['depth']} | `{EXAMPLE_NAMES.get(sid, sid)}.md` / `.json` / `.opml` / `.mm` |" for sid, d in data.items())
        + "\n", encoding="utf-8", newline="\n")
    return written


def root_index_html(credits):
    """The repository-root index.html (meta refresh -> play/index.html), rendered from the template so the
    release zip carries the same file as the repository: unzip, double-click index.html, and it opens play/."""
    for tpl in (ROOT / "tools" / "templates" / "index.html.tmpl", ROOT / "tools" / "publish_templates" / "index.html.tmpl"):
        if tpl.exists():
            text = tpl.read_text(encoding="utf-8")
            return re.sub(r"\{\{([A-Z0-9_]+)\}\}", lambda m: str(credits.get(m.group(1), m.group(0))), text)
    return None


def make_zip(credits, out_dir=None):
    """release/<repo>-v<version>.zip = index.html (root redirect) + play/**. ASCII file name (GitHub strips non-ASCII)."""
    out_dir = Path(out_dir) if out_dir else RELEASE
    out_dir.mkdir(exist_ok=True, parents=True)
    name = f"{credits.get('REPO_NAME', 'markdown-mindmap')}-v{credits.get('VERSION', '1.0')}.zip"
    out = out_dir / name
    entries = []
    root_index = root_index_html(credits)
    if root_index is not None:
        entries.append(("index.html", root_index.encode("utf-8")))
    for p in sorted(p for p in PLAY.rglob("*") if p.is_file()):
        entries.append(("play/" + p.relative_to(PLAY).as_posix(), p.read_bytes()))
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for arcname, data in entries:
            info = zipfile.ZipInfo(arcname, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    size = out.stat().st_size
    if size > ZIP_LIMIT:
        raise SystemExit(f"release zip is {size} bytes > 15 MB limit")
    return out, size, len(entries)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--release", action="store_true", help="also build the release zip")
    args = ap.parse_args(argv)
    credits = load_credits()
    print("wrote", write_credits_js(credits).relative_to(ROOT).as_posix())
    ex = export_examples()
    if ex:
        print(f"wrote docs/examples/ ({len(ex)} files)")
    total = sum(p.stat().st_size for p in PLAY.rglob("*") if p.is_file())
    print(f"play/ = {total} bytes")
    if args.release:
        out, size, n = make_zip(credits)
        print(f"wrote {out.relative_to(ROOT).as_posix()}: {n} files, {size} bytes")


if __name__ == "__main__":
    main()
